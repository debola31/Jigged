/**
 * Geographic reference data for address forms.
 *
 * - `COUNTRIES`: ISO 3166-1 countries (alpha-2 code + display name).
 * - `US_STATES` / `CA_PROVINCES`: subdivisions for the two countries we have
 *   dropdowns for. Other countries fall back to a free-text state field.
 *
 * Used by the shared `CountrySelect` / `StateSelect` components.
 */

export interface Country {
  /** ISO 3166-1 alpha-2 code, e.g. "US". */
  code: string;
  /** Display name. */
  name: string;
}

export interface Subdivision {
  /** Postal abbreviation, e.g. "CA" (California) or "ON" (Ontario). */
  code: string;
  name: string;
}

